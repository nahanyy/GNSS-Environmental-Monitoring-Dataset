"""
Visualization of GPS C/N0 skyplot heatmap.

This script generates the C/N0 heatmap shown in Fig. 7 of the paper.
It reads the satelliteInformation files generated by Process-1.py,
extracts GPS C/N0, elevation, and azimuth observations, and visualizes
the spatial distribution of mean C/N0 values in the sky domain.
"""
import json
import re
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap, Normalize
from matplotlib.cm import ScalarMappable


# Input directories containing satelliteInformation files.
# Multiple folders can be provided to concatenate observations
# from different days.
INPUT_DIRS = [
    Path(r"../Dataset/Processed_Data/7_31"),
    Path(r"../Dataset/Processed_Data/8_1"),
]

OUTPUT_DIR = Path(r"../Visualization/results")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

OUTPUT_PNG = OUTPUT_DIR / "GPS_CNO.png"

# True:
#     Automatically read all available satelliteInformation files.
#
# False:
#     Only read files specified by HOURS_TO_USE.
READ_ALL_EXISTING_FILES = True


HOURS_TO_USE = range(24)

NUM_GPS_SATS = 32

AZ_BIN_SIZE = 30    
EL_BIN_SIZE = 15    

USE_PERCENTILE_COLOR_RANGE = True
LOW_PERCENTILE = 5
HIGH_PERCENTILE = 95


def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def satellite_file_sort_key(path):
    m = re.search(r"satelliteInformation(\d+)", path.stem)
    if m:
        return int(m.group(1))
    return 999


def collect_satellite_files(input_dirs, hours_to_use=None, read_all_existing=True):
    all_files = []

    for day_idx, input_dir in enumerate(input_dirs):
        if not input_dir.exists():
            print(f"[Skip] Folder does not exist: {input_dir}")
            continue

        if read_all_existing:
            files = list(input_dir.glob("satelliteInformation*.json"))
            files = sorted(files, key=satellite_file_sort_key)

            if not files:
                print(f"[Info] No satelliteInformation*.json files found in: {input_dir}")
                continue

            print(f"\nReading folder {day_idx + 1}: {input_dir}")
            for f in files:
                print(f"  {f.name}")

            all_files.extend(files)

        else:
            if hours_to_use is None:
                hours_to_use = range(24)

            print(f"\nReading folder {day_idx + 1}: {input_dir}")
            files = []

            for hour in hours_to_use:
                file_path = input_dir / f"satelliteInformation{hour}.json"
                if file_path.exists():
                    files.append(file_path)
                    print(f"  {file_path.name}")
                else:
                    print(f"  [Skip] File does not exist: {file_path.name}")

            files = sorted(files, key=satellite_file_sort_key)
            all_files.extend(files)

    print(f"\nTotal number of satelliteInformation files collected: {len(all_files)}")

    return all_files


def build_cno_grid(files):

    az_edges = np.arange(0, 360 + AZ_BIN_SIZE, AZ_BIN_SIZE)
    el_edges = np.arange(0, 90 + EL_BIN_SIZE, EL_BIN_SIZE)

    n_az = len(az_edges) - 1   # 12
    n_el = len(el_edges) - 1   # 6

    sum_grid = np.zeros((n_el, n_az), dtype=float)
    count_grid = np.zeros((n_el, n_az), dtype=int)

    total_valid_points = 0

    for file_path in files:
        print(f"Processing: {file_path}")
        data = load_json(file_path)

        cno_all = data.get("cno_G", [])
        elev_all = data.get("elev_G", [])
        azim_all = data.get("azim_G", [])

        n = min(len(cno_all), len(elev_all), len(azim_all))
        if n == 0:
            print(f"[Skip] File missing cno_G / elev_G / azim_G: {file_path}")
            continue

        for i in range(n):
            cno_row = cno_all[i]
            elev_row = elev_all[i]
            azim_row = azim_all[i]

            if len(cno_row) < NUM_GPS_SATS:
                cno_row = cno_row + [0] * (NUM_GPS_SATS - len(cno_row))
            if len(elev_row) < NUM_GPS_SATS:
                elev_row = elev_row + [0] * (NUM_GPS_SATS - len(elev_row))
            if len(azim_row) < NUM_GPS_SATS:
                azim_row = azim_row + [0] * (NUM_GPS_SATS - len(azim_row))

            cno_row = cno_row[:NUM_GPS_SATS]
            elev_row = elev_row[:NUM_GPS_SATS]
            azim_row = azim_row[:NUM_GPS_SATS]

            for sat_idx in range(NUM_GPS_SATS):
                cno = cno_row[sat_idx]
                elev = elev_row[sat_idx]
                azim = azim_row[sat_idx]

                if cno is None or elev is None or azim is None:
                    continue

                try:
                    cno = float(cno)
                    elev = float(elev)
                    azim = float(azim)
                except Exception:
                    continue

                if cno <= 0:
                    continue

                if elev < 0 or elev > 90:
                    continue

                azim = azim % 360.0

                az_idx = int(azim // AZ_BIN_SIZE)
                if az_idx >= n_az:
                    az_idx = n_az - 1

                if elev == 90:
                    el_idx = n_el - 1
                else:
                    el_idx = int(elev // EL_BIN_SIZE)
                    if el_idx >= n_el:
                        el_idx = n_el - 1

                sum_grid[el_idx, az_idx] += cno
                count_grid[el_idx, az_idx] += 1
                total_valid_points += 1

    mean_grid = np.full_like(sum_grid, np.nan, dtype=float)
    valid_mask = count_grid > 0
    mean_grid[valid_mask] = sum_grid[valid_mask] / count_grid[valid_mask]

    print(f"\nTotal valid samples: {total_valid_points}")
    print(f"Number of non-empty bins: {np.sum(valid_mask)} / {mean_grid.size}")

    return mean_grid, count_grid


def create_red_colormap():

    colors = [
        "#fff0f3", 
        "#fde0dd",
        "#fcbba1",
        "#fb6a4a",
        "#de2d26",
        "#a50f15"
    ]

    cmap = LinearSegmentedColormap.from_list("lightpink_red", colors)

    cmap.set_bad(color="#ffffff")

    cmap.set_under(color="#fff0f3")

    cmap.set_over(color="#a50f15")

    return cmap

def plot_skyplot_heatmap(mean_grid, count_grid, output_png):
    fig, ax = plt.subplots(figsize=(8.5, 8.5), subplot_kw={"projection": "polar"})

    ax.set_theta_zero_location("N")
    ax.set_theta_direction(-1)

    finite_vals = mean_grid[np.isfinite(mean_grid)]
    if len(finite_vals) == 0:
        print("No valid data to plot.")
        return

    if USE_PERCENTILE_COLOR_RANGE and len(finite_vals) >= 5:
        vmin = np.percentile(finite_vals, LOW_PERCENTILE)
        vmax = np.percentile(finite_vals, HIGH_PERCENTILE)

        if vmin == vmax:
            vmin = np.min(finite_vals)
            vmax = np.max(finite_vals)
    else:
        vmin = np.min(finite_vals)
        vmax = np.max(finite_vals)

    print(f"\nColor mapping range: vmin = {vmin:.3f}, vmax = {vmax:.3f}")

    norm = Normalize(vmin=vmin, vmax=vmax)
    cmap = create_red_colormap()

    for el_idx in range(mean_grid.shape[0]):
        for az_idx in range(mean_grid.shape[1]):
            value = mean_grid[el_idx, az_idx]

            el_low = el_idx * EL_BIN_SIZE
            el_high = (el_idx + 1) * EL_BIN_SIZE

            r_outer = 90 - el_low
            r_inner = 90 - el_high

            bottom = r_inner
            height = r_outer - r_inner

            az_low = az_idx * AZ_BIN_SIZE
            az_high = (az_idx + 1) * AZ_BIN_SIZE
            theta_center = np.deg2rad((az_low + az_high) / 2.0)
            width = np.deg2rad(AZ_BIN_SIZE)

            if np.isnan(value):
                color = "#ffffff"
            else:
                color = cmap(norm(value))

            ax.bar(
                theta_center,
                height,
                width=width,
                bottom=bottom,
                color=color,
                edgecolor="none",
                linewidth=0,
                align="center"
            )

    ax.set_ylim(0, 90)

    ax.set_thetagrids(np.arange(0, 360, 30), fontsize=11)

    radial_ticks = [15, 30, 45, 60, 75, 90]
    radial_labels = ["75°", "60°", "45°", "30°", "15°", "0°"]
    ax.set_rgrids(radial_ticks, labels=radial_labels, angle=22.5, fontsize=11)

    ax.text(0, 0, "90°", ha="center", va="center", fontsize=11)

    ax.grid(True, linestyle="--", linewidth=1.0, color="#b3b3b3", alpha=0.9)
    ax.set_axisbelow(False)

    ax.set_title("GPS Mean C/N0 Skyplot Heatmap", fontsize=18, pad=22)

    sm = ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])

    cbar = plt.colorbar(sm, ax=ax, pad=0.10, shrink=0.88)
    cbar.set_label("Mean C/N0 (dB-Hz)", fontsize=12)
    cbar.ax.tick_params(labelsize=11)

    plt.tight_layout()
    plt.savefig(output_png, dpi=300, bbox_inches="tight")
    plt.show()

    print(f"\nImage saved to: {output_png}")

def main():
    files = collect_satellite_files(
        input_dirs=INPUT_DIRS,
        hours_to_use=HOURS_TO_USE,
        read_all_existing=READ_ALL_EXISTING_FILES
    )

    if not files:
        print("No satelliteInformation files found.")
        return

    mean_grid, count_grid = build_cno_grid(files)

    print("\nMean grid (rows = elevation bins, columns = azimuth bins):")
    print(mean_grid)

    print("\nCount grid (number of valid samples per bin):")
    print(count_grid)

    plot_skyplot_heatmap(mean_grid, count_grid, OUTPUT_PNG)

if __name__ == "__main__":
    main()