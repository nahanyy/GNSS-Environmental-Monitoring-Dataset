"""
Visualization of visible satellite number variations.

This script generates the figure corresponding to Fig. 8 in the paper:
"Time variations in the number of visible satellites for each constellation".

The script reads the satelliteInformation files generated by Process-1.py,
extracts the svUsed information for different GNSS constellations, and
visualizes the temporal variations of the number of used satellites.

The supported constellations include:
GPS, Galileo, BeiDou (BDS), and GLONASS.
"""
import json
import re
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator



INPUT_DIR = Path(r"../Dataset/Processed_Data/5_7")
OUTPUT_PNG = INPUT_DIR / "s22.png"

CONSTELLATIONS = {
    "G": "GPS",
    "E": "Galileo",
    "B": "BDS",
    "R": "GLONASS",
}


FIGSIZE = (8.0, 3.2)
DPI = 300
LINEWIDTH = 2.3

RESAMPLE_SECONDS = 60

SHOW_LEGEND = False
SHOW_GRID = True

def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def file_index(path: Path):
    m = re.search(r"satelliteInformation(\d+)\.json$", path.name, re.IGNORECASE)
    return int(m.group(1)) if m else 10**9


def normalize_key(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def to_float_array(x):
    arr = np.asarray(x, dtype=object)

    def conv(v):
        if v is None:
            return np.nan
        if isinstance(v, str):
            v = v.strip()
            if v == "" or v.lower() in ["nan", "none", "null"]:
                return np.nan
        try:
            return float(v)
        except Exception:
            return np.nan

    return np.vectorize(conv, otypes=[float])(arr)


def find_svused_key(data, const_code):

    if const_code in data and isinstance(data[const_code], dict):
        sub = data[const_code]
        for k in sub.keys():
            nk = normalize_key(k)
            if "svused" in nk:
                return (const_code, k)

    targets = [
        f"svUsed_{const_code}",
        f"{const_code}_svUsed",
        f"svused_{const_code}",
        f"{const_code}_svused",
        f"svUsed{const_code}",
        f"{const_code}svUsed",
        f"svused{const_code}",
        f"{const_code}svused",
    ]
    target_norms = [normalize_key(t) for t in targets]

    for k in data.keys():
        nk = normalize_key(k)
        if nk in target_norms:
            return (None, k)

    for k in data.keys():
        nk = normalize_key(k)
        if const_code.lower() in nk and "svused" in nk:
            return (None, k)

    raise KeyError(f"Could not find svUsed field for constellation {const_code}. Please check the JSON keys.")


def get_svused_matrix(data, const_code):
    parent_key, svused_key = find_svused_key(data, const_code)

    if parent_key is None:
        svused = data[svused_key]
        print(f"{const_code}: using field {svused_key}")
    else:
        svused = data[parent_key][svused_key]
        print(f"{const_code}: using field {parent_key}/{svused_key}")

    svused = to_float_array(svused)
    svused = np.squeeze(svused)

    if svused.ndim != 2:
        raise ValueError(
            f"The svUsed field for constellation {const_code} is not a 2D matrix, current shape: {svused.shape}"
        )

    return svused


def count_used_from_svused(svused):
    valid = np.isfinite(svused) & (svused == 1)

    if svused.shape[1] >= svused.shape[0]:
        counts = np.sum(valid, axis=0)
    else:
        counts = np.sum(valid, axis=1)

    return counts.astype(float)


def resample_mean(y, step):
    y = np.asarray(y, dtype=float)
    if step <= 1:
        return y

    n = len(y)
    m = n // step
    if m == 0:
        return y

    y = y[:m * step]
    y = y.reshape(m, step)
    return np.nanmean(y, axis=1)

files = sorted(INPUT_DIR.glob("satelliteInformation*.json"), key=file_index)

if len(files) == 0:
    raise FileNotFoundError(f"No satelliteInformation*.json found in {INPUT_DIR}")

print(f"Found {len(files)} files:")
for f in files:
    print("  ", f.name)

series_dict = {c: [] for c in CONSTELLATIONS}

for fp in files:
    print(f"\nReading: {fp.name}")
    data = load_json(fp)

    for const_code in CONSTELLATIONS:
        svused = get_svused_matrix(data, const_code)
        counts = count_used_from_svused(svused)
        series_dict[const_code].append(counts)

for const_code in CONSTELLATIONS:
    y = np.concatenate(series_dict[const_code])
    y = resample_mean(y, RESAMPLE_SECONDS)
    series_dict[const_code] = y

    print(
        f"{CONSTELLATIONS[const_code]}: "
        f"min={np.nanmin(y):.2f}, "
        f"max={np.nanmax(y):.2f}, "
        f"mean={np.nanmean(y):.2f}"
    )

n_points = len(next(iter(series_dict.values())))
x_hours = np.arange(n_points) * RESAMPLE_SECONDS / 3600.0

fig, ax = plt.subplots(figsize=FIGSIZE, dpi=DPI)

for const_code, const_name in CONSTELLATIONS.items():
    ax.plot(
        x_hours,
        series_dict[const_code],
        linewidth=LINEWIDTH,
        label=const_name,
    )

ax.set_xlim(0, 24)
ax.set_xticks(np.arange(0, 25, 2))
ax.yaxis.set_major_locator(MaxNLocator(integer=True))

ax.set_xlabel("Elapsed time (h)", fontsize=12)
ax.set_ylabel("Used satellites", fontsize=12)

if SHOW_GRID:
    ax.grid(True, linestyle="--", linewidth=0.6, alpha=0.35)

ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)
ax.tick_params(axis="both", labelsize=11)

if SHOW_LEGEND:
    ax.legend(frameon=False, fontsize=10)

plt.tight_layout()
plt.savefig(OUTPUT_PNG, dpi=DPI, bbox_inches="tight")
plt.show()

print(f"\nImage saved: {OUTPUT_PNG}")